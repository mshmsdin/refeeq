conn = sqlite3.connect(DB_PATH)
conn.row_factory = sqlite3.Row
cur = conn.cursor()

# Get current state of each folder
updated = 0
for folder_id, target_cat in ID_TO_CATEGORY.items():
    cur.execute("SELECT id, name, path, parent_path FROM folders WHERE id=? AND sect='شيعة'", (folder_id,))
    row = cur.fetchone()
    if not row:
        continue
    
    current = dict(row)
    if current['parent_path'] == target_cat:
        continue  # already correct
    
    old_path = current['path']
    folder_name = current['name']
    new_path = target_cat + "\\" + folder_name
    
    # Update this folder
    cur.execute("UPDATE folders SET parent_path=?, path=? WHERE id=?",
                (target_cat, new_path, folder_id))
    
    # Update children paths
    cur.execute("SELECT id, path, parent_path FROM folders WHERE path LIKE ? AND id!=?",
                (old_path + "\\%", folder_id))
    for child in cur.fetchall():
        new_child_path = new_path + child['path'][len(old_path):]
        new_child_parent = child['parent_path']
        if new_child_parent == old_path:
            new_child_parent = new_path
        elif new_child_parent.startswith(old_path + "\\"):
            new_child_parent = new_path + new_child_parent[len(old_path):]
        cur.execute("UPDATE folders SET path=?, parent_path=? WHERE id=?",
                    (new_child_path, new_child_parent, child['id']))
    
    updated += 1

conn.commit()

# Final count
cur.execute("SELECT COUNT(*) as c FROM folders WHERE sect='شيعة' AND parent_path='متنوع'")
remaining = cur.fetchone()['c']

# Export final structure to JSON
cur.execute("""
    SELECT f1.name as category, COUNT(f2.id) as folder_count
    FROM folders f1
    LEFT JOIN folders f2 ON f2.parent_path=f1.name AND f2.sect='شيعة'
    WHERE f1.sect='شيعة' AND (f1.parent_path IS NULL OR f1.parent_path='')
    GROUP BY f1.name ORDER BY f1.name
""")
final = [dict(r) for r in cur.fetchall()]

with open('final_structure.json', 'w', encoding='utf-8') as fp:
    json.dump(final, fp, ensure_ascii=False, indent=2)

print(f"Updated: {updated}")
print(f"Remaining in متنوع: {remaining}")
print(f"Final structure saved to final_structure.json")
conn.close()
