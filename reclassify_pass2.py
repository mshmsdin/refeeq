conn = sqlite3.connect(DB_PATH)
conn.row_factory = sqlite3.Row
cur = conn.cursor()

# Get all folders currently under 'متنوع'
cur.execute("""
    SELECT id, name, path, parent_path FROM folders
    WHERE sect = 'شيعة' AND parent_path = 'متنوع'
    ORDER BY name
""")
unclassified = [dict(r) for r in cur.fetchall()]
print(f"Reclassifying {len(unclassified)} 'متنوع' folders...")

def reclassify(name):
    for cat_name, keywords in EXTENDED_KEYWORDS.items():
        for kw in keywords:
            if kw in name:
                return cat_name
    return "متنوع"

# Get category folder IDs
cur.execute("""
    SELECT id, name FROM folders
    WHERE sect = 'شيعة' AND (parent_path IS NULL OR parent_path = '')
""")
cat_map = {r["name"]: r["id"] for r in cur.fetchall()}
print(f"Available categories: {list(cat_map.keys())}")

reclassified = 0
still_unclassified = []

for folder in unclassified:
    new_cat = reclassify(folder["name"])
    if new_cat != "متنوع":
        new_parent = new_cat
        # Reconstruct new path: newCat\folderName
        folder_name = folder["name"]
        new_path = new_cat + "\\" + folder_name
        
        cur.execute("""
            UPDATE folders SET parent_path = ?, path = ? WHERE id = ?
        """, (new_parent, new_path, folder["id"]))
        
        # Also update children of this folder
        old_path_prefix = folder["path"]
        cur.execute("""
            SELECT id, path, parent_path FROM folders
            WHERE path LIKE ? AND id != ?
        """, (old_path_prefix + "\\%", folder["id"]))
        children = cur.fetchall()
        
        for child in children:
            old_child_path = child["path"]
            new_child_path = new_path + old_child_path[len(old_path_prefix):]
            old_child_parent = child["parent_path"]
            if old_child_parent == old_path_prefix:
                new_child_parent = new_path
            else:
                new_child_parent = new_path + old_child_parent[len(old_path_prefix):]
            cur.execute("""
                UPDATE folders SET path = ?, parent_path = ? WHERE id = ?
            """, (new_child_path, new_child_parent, child["id"]))
        
        reclassified += 1
    else:
        still_unclassified.append(folder["name"])

conn.commit()
print(f"\nReclassified: {reclassified}")
print(f"Still in 'متنوع': {len(still_unclassified)}")
print("\nStill unclassified:")
for name in sorted(still_unclassified):
    print(f"  - {name}")

conn.close()
