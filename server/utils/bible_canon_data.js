/**
 * Returns precise church recognition and canon status for any book code.
 */
export function getCanonInfoForBook(code, collectionSlug = null) {
  if (BOOK_CANON_DATA[code]) {
    return BOOK_CANON_DATA[code];
  }

  // Determine based on collection / book code
  const isNewTestament = [
    'MAT','MRK','LUK','JHN','ACT','ROM','1CO','2CO','GAL','EPH',
    'PHP','COL','1TH','2TH','1TI','2TI','TIT','PHM','HEB','JAS',
    '1PE','2PE','1JN','2JN','3JN','JUD','REV'
  ].includes(code) || collectionSlug === 'new-testament';

  if (isNewTestament) {
    return {
      is_disputed: false,
      category_name: 'أسفار العهد الجديد (New Testament)',
      accepted_by: [
        'جميع الكنائس المسيحية الكبرى ذات التقليد القانوني المتداول اليوم، ومنها الكاثوليكية والأرثوذكسية الشرقية والمشرقية والبروتستانتية والكنائس السريانية والإثيوبية.'
      ],
      rejected_by: [],
      notes: 'سفر قانوني معتمد موثق في أقدم البرديات والمخطوطات اليونانية الكبرى (مثل السينائية والفاتيكانية والإسكندرية) ومجمع عليه لدى كافة التقاليد المسيحية الكبرى المعاصرة.'
    };
  }

  // Old Testament Protocanonical Books (39 books)
  return {
    is_disputed: false,
    category_name: 'الأسفار القانونية الأولى للعهد القديم (Protocanonical)',
    accepted_by: [
      'جميع الكنائس المسيحية الكبرى ذات التقليد القانوني المتداول اليوم، ومنها الكاثوليكية والأرثوذكسية الشرقية والمشرقية والبروتستانتية والكنائس السريانية والإثيوبية.',
      'التقليد اليهودي الحاخامي (ضمن أسفار التناخ الـ 24 في النص الماسوري العبري: التوراة، الأنبياء، والكتب).'
    ],
    rejected_by: [],
    notes: 'سفر قانوني أصيل مكتوب بالعبرية/الآرامية، وموثق في مخطوطات قمران القديمة والترجمة السبعينية اليونانية (LXX) والنص الماسوري والفولغاتا.'
  };
}
