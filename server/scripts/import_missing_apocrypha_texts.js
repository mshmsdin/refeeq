const insertVerse = db.prepare(`
  INSERT OR REPLACE INTO bible_verses (translation_id, book_code, chapter, verse, text, search_text)
  VALUES (?, ?, ?, ?, ?, ?)
`);

const versesBatch = [];
function addVerse(tid, bookCode, ch, v, text) {
  versesBatch.push({
    tid,
    bookCode,
    chapter: ch,
    verse: v,
    text,
    searchText: normalizeArabicText(text)
  });
}

