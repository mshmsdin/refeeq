import Database from "better-sqlite3";
const db = new Database("./db/library.db");

console.log("═══════════════════════════════════════════════════════════");
console.log("🔄 إعادة تصنيف قسم الإلحاد — من كتب إلى موضوعات منطقية");
console.log("═══════════════════════════════════════════════════════════");

const allDocs = db.prepare("SELECT id, filename, folder_path, folder_name, book_source FROM documents WHERE sect=\'" + "إلحاد\'" + " ORDER BY id").all();
console.log("📄 إجمالي الوثائق:", allDocs.length);

function classifyDoc(doc) {
  const fp = doc.folder_path || "";
  const fn = doc.filename || "";
  const text = fn + " " + fp;

  // باب الدفاع — أدلة وجود الله
  if (/دليل|وجود الله|وجود الخالق|الإيجاد|دليل الفطرة|دليل الكون|دليل التصميم|كيف نعرف الله|القواعد العقلية|الإيمان بالله/.test(fn)) return ["الدفاع", "أدلة وجود الله"];
  if (/الجزء الأول|أدلة وجود/.test(fp)) return ["الدفاع", "أدلة وجود الله"];

  // باب الدفاع — صحة الإسلام
  if (/رسول|النبي|بشارة|إعجاز|قرآن|توحيد|ظهر الدين|الإخبار|المغيبات|معجزة|صحة الإسلام|السنة|سابقين/.test(fn)) return ["الدفاع", "صحة الإسلام وأدلة نبوة النبي"];
  if (/رسول الأميين|الإعجاز العلمي|أعظم برهان|الإخبار|كيف ظهر|بصائر صحة|الجزء الثاني/.test(fp)) return ["الدفاع", "صحة الإسلام وأدلة نبوة النبي"];

  // باب الدفاع — أصول الاستدلال
  if (/وسواس|شبهة|منهج|استدلال|يقين|لماذا أنا مسلم|منكرو السنة|علاج الوسواس|الفرق بين/.test(fn)) return ["الدفاع", "أصول الاستدلال ومنهج الشبهات"];
  if (/الوسواس القهري|يقينية الإيمان|الإسلام والإلحاد وجهاً لوجه/.test(fp)) return ["الدفاع", "أصول الاستدلال ومنهج الشبهات"];

  // باب الإلزام — أخلاقيات
  if (/أخلاق|قيم|تحريم|يُحرّم|الإرادة الحرة|مسؤولية|عقوبة|جريمة|قانون الجذب|حرية|أيهما أكرم|قوامة|تعدد الزوجات|المثلية|مثلية|الحب والكراهية/.test(fn)) return ["الإلزام", "تناقضات الإلحاد الأخلاقية"];

  // باب الإلزام — علمية
  if (/تطور|داروين|صدفة|العلموية|بيلتداون|نبراسكا|هايكل|أجنة|فراشة|التزوير|خطأ في نظرية|أخطاء/.test(fn)) return ["الإلزام", "تناقضات الإلحاد العلمية والفلسفية"];
  if (/أخطاء|تزوير|40 خطأ/.test(fp)) return ["الإلزام", "تناقضات الإلحاد العلمية والفلسفية"];

  // باب الإلزام — لوازم المذهب
  if (/لوازم|مادي|ثمار الإلحاد|نتائج الإلحاد|كفر بالأنبياء|هل يكفي|الغيب|جبريل|دليل يقبله/.test(fn)) return ["الإلزام", "إلزام الملحد بلوازم مذهبه"];
  if (/الجزء الثالث|الرد على أشهر شبهات/.test(fp)) return ["الإلزام", "إلزام الملحد بلوازم مذهبه"];

  // باب الهجوم — فضائح رموز
  if (/دوكينز|سينجر|هاريس|هيتشنز|دينيت|كهنة|رموز الإلحاد|فضائح/.test(fn)) return ["الهجوم", "فضائح رموز الإلحاد الجديد"];

  // باب الهجوم — تزوير علمي
  if (/تزوير|بيلتداون|نبراسكا|هايكل الأجنة|الفراشات/.test(fn)) return ["الهجوم", "تزوير الأدلة التطورية"];

  // باب الهجوم — أيديولوجيات
  if (/تنوير|نسوية|المثلية الجنسية|الجذب|طاقة|نباتية|التحرش|فكر ضال|أفكار ضالة/.test(fn)) return ["الهجوم", "الأيديولوجيات الضالة المعاصرة"];
  if (/أفكار ضالة/.test(fp)) return ["الهجوم", "الأيديولوجيات الضالة المعاصرة"];

  // افتراضي بحسب الكتاب
  if (/الجزء الأول/.test(fp)) return ["الدفاع", "أدلة وجود الله"];
  if (/الجزء الثاني/.test(fp)) return ["الدفاع", "صحة الإسلام وأدلة نبوة النبي"];
  if (/الجزء الثالث/.test(fp)) return ["الإلزام", "إلزام الملحد بلوازم مذهبه"];

  return ["الدفاع", "أصول الاستدلال ومنهج الشبهات"];
}

const categorized = {};
for (const doc of allDocs) {
  const [main, sub] = classifyDoc(doc);
  if (!categorized[main]) categorized[main] = {};
  if (!categorized[main][sub]) categorized[main][sub] = [];
  categorized[main][sub].push(doc);
}

let total = 0;
for (const [main, subs] of Object.entries(categorized)) {
  const cnt = Object.values(subs).reduce((s, a) => s + a.length, 0);
  total += cnt;
  console.log("\n📂", main, "(" + cnt + ")");
  for (const [sub, docs] of Object.entries(subs)) {
    console.log("   📁", sub, "(" + docs.length + ")");
    docs.slice(0,2).forEach(d => console.log("      -", d.filename));
  }
}
console.log("\n✅ المجموع:", total);
db.close();
